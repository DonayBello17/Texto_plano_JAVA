    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try (FileWriter fw = new FileWriter("tareas.txt", true);
             PrintWriter pw = new PrintWriter(fw)) {

            // Guardar directamente lo que haya en el JTextField
            String texto = jTextField1.getText();
            pw.println(texto); 

            // Mostrarlo también en el área de texto
            jTextArea1.append("Guardado: " + texto + "\n");

            // Limpiar el campo para escribir otra tarea
            jTextField1.setText("");

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Error al guardar.");
        }

    }//GEN-LAST:event_jButton1ActionPerformed

